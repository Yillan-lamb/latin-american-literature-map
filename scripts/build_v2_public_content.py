    return {
        "content": content,
        "status": status,
        "research_refs": research,
        "source_refs": sources,
        "basis_note": note,
        "reviewer": reviewer,
        "created_at": DATE,
        "reviewed_at": DATE if status == "auto_approved" and reviewer != "UNREVIEWED" else None,
    }


