def normalize_wcd03_display_names(value):
    """Project reviewed names into curation without rewriting old change sets."""
    if isinstance(value, str):
        for old, new in WCD03_DISPLAY_REPLACEMENTS.items():
            value = value.replace(old, new)
        return value
    if isinstance(value, list):
        return [normalize_wcd03_display_names(item) for item in value]
    if isinstance(value, dict):
        return {key: normalize_wcd03_display_names(item) for key, item in value.items()}
    return value


def load_place_provenance(expected_targets: set[str]) -> dict[str, dict[str, list[str]]]:
    payload = json.loads(PLACE_PROVENANCE.read_text(encoding="utf-8"))
    if payload.get("schema_version") != "v2-public-content-place-provenance-0.1":
        raise ValueError("unexpected place provenance schema")
    places = payload.get("places")
    if not isinstance(places, dict) or set(places) != expected_targets:
        raise ValueError("place provenance targets do not match PLACE_MEANINGS")
    for target_id, mapping in places.items():
        if not isinstance(mapping, dict) or "default" not in mapping:
            raise ValueError(f"missing default place provenance: {target_id}")
        if not set(mapping) <= PLACE_CONTENT_FIELDS | {"default"}:
            raise ValueError(f"unexpected place provenance field: {target_id}")
        for field_key, refs in mapping.items():
            if not isinstance(refs, list) or len(refs) != len(set(refs)):
                raise ValueError(f"invalid place provenance refs: {target_id}/{field_key}")
            if any(not isinstance(ref, str) or not ref.startswith("V1-REL-") for ref in refs):
                raise ValueError(f"invalid place provenance id: {target_id}/{field_key}")
    return places


def place_field_refs(
    provenance: dict[str, dict[str, list[str]]], target_id: str, field_key: str
) -> list[str]:
    mapping = provenance[target_id]
    return list(mapping.get(field_key, mapping["default"]))


def field(content, research, sources, status="user_review", note="新增长篇公共文案，等待 USER 集中审核", reviewer="UNREVIEWED"):
    research = [item for item in research if item not in {"V1-FCT-0218", "V1-FCT-0231", "V1-FCT-0238"}]
    return {
        "content": content,
        "status": status,
        "research_refs": research,
        "source_refs": sources,
        "basis_note": note,
        "reviewer": reviewer,
        "created_at": DATE,
        "reviewed_at": DATE if status == "auto_approved" and reviewer != "UNREVIEWED" else None,
    }


def user_field(content, research, sources, note="USER 在 rc.5 内容密度审核中明确批准"):
    return field(content, research, sources, "auto_approved", note, "USER")


def feature(title, text):
    return {"title": title, "text": text}


def next_read(target_id, reason):
    return {"target_id": target_id, "reason": reason}


def flatten_text(value):
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        return " ".join(flatten_text(item) for item in value)
    if isinstance(value, dict):
        return " ".join(flatten_text(item) for item in value.values())
    return ""


def downgrade_low_value_curation(payload):
    """Hold template-like literary advice while preserving historical batch inputs."""
    for group, field_names in JUDGMENT_FIELDS.items():
        for record in payload[group]:
            for field_name in field_names:
                wrapped = record.get(field_name)
                if not isinstance(wrapped, dict) or wrapped.get("reviewer") == "USER":
                    continue
                content = flatten_text(wrapped.get("content"))
                if not any(pattern in content for pattern in LOW_VALUE_CURATION_PATTERNS):
                    continue
                wrapped["status"] = "hold"
                wrapped["reviewer"] = "CODEX-REVIEW"
                wrapped["reviewed_at"] = None
                wrapped["basis_note"] = (
                    "Web 0.2.0 consolidation: low-value template wording withheld; "
                    "retain only the research-basic page until work-level evidence supports literary guidance"
                )


